package com.memetrade.audit.api;

import com.memetrade.shared.wallet.WalletAddress;
import java.time.Instant;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;

/**
 * One audit event as defined by contract C9 (J6 since u2-retention). {@code details} never carries a secret, token,
 * nonce or signature (BR4.3) nor a full wallet address (BR2.3); {@code actor} uses the masked form of a wallet.
 *
 * <p>u2-retention (BR2.1, J6): an event that involves a wallet carries it in {@code wallet}, its own field, only for a
 * valid address. That field is never serialised: the publisher turns it into the {@code walletHmac} of the outbox
 * payload (HMAC-SHA-256 with the key of the configuration) and the trail never holds the full address. Text that is not
 * a wallet never goes there (BR2.15).
 *
 * @param eventId generated by the caller; an idempotent retry reuses it and the trail keeps a single copy
 * @param tenantId empty only before login (with {@link ActorType#ANONYMOUS}) and for global administrator actions
 * @param actor userId, adminId, masked address (before login) or {@code "system"}
 * @param occurredAt UTC instant from the injectable clock
 * @param wallet the full address of the wallet the event involves, or {@code null}; never serialised or printed
 */
public record AuditEventCommand(
        UUID eventId,
        Optional<UUID> tenantId,
        String actor,
        ActorType actorType,
        String action,
        String targetRef,
        String correlationId,
        Instant occurredAt,
        Map<String, String> details,
        String wallet,
        RealReferences real) {

    /**
     * An event with or without a wallet and without typed REAL references (every event before 261113-trading-real-bot).
     */
    public AuditEventCommand(
            UUID eventId,
            Optional<UUID> tenantId,
            String actor,
            ActorType actorType,
            String action,
            String targetRef,
            String correlationId,
            Instant occurredAt,
            Map<String, String> details,
            String wallet) {
        this(eventId, tenantId, actor, actorType, action, targetRef, correlationId, occurredAt, details, wallet, null);
    }

    /** 261113-trading-real-bot (M8, BR6.2): the same event with typed REAL references. */
    public AuditEventCommand withReal(RealReferences references) {
        return new AuditEventCommand(
                eventId,
                tenantId,
                actor,
                actorType,
                action,
                targetRef,
                correlationId,
                occurredAt,
                details,
                wallet,
                references);
    }

    /** Detail keys that are never accepted, whatever their value (BR4.3). */
    static final Set<String> FORBIDDEN_DETAIL_KEYS = Set.of(
            "nonce",
            "signature",
            "token",
            "accesstoken",
            "refreshtoken",
            "authorization",
            "password",
            "secret",
            "privatekey",
            "seedphrase",
            "mnemonic",
            "message");

    public AuditEventCommand {
        Objects.requireNonNull(eventId, "eventId");
        Objects.requireNonNull(tenantId, "tenantId");
        Objects.requireNonNull(actorType, "actorType");
        Objects.requireNonNull(occurredAt, "occurredAt");
        requireText(actor, "actor");
        requireText(action, "action");
        requireText(correlationId, "correlationId");
        details = Map.copyOf(details == null ? Map.of() : details);
        for (String key : details.keySet()) {
            if (FORBIDDEN_DETAIL_KEYS.contains(key.toLowerCase(Locale.ROOT))) {
                throw new IllegalArgumentException("Audit details must not contain the key " + key);
            }
        }
        if (actorType == ActorType.ANONYMOUS && tenantId.isPresent()) {
            throw new IllegalArgumentException("Anonymous (pre-login) events carry no tenant");
        }
        if (wallet != null && !WalletAddress.isValid(wallet)) {
            // BR2.15: the HMAC is never computed over text that is not a wallet; the value is not echoed.
            throw new IllegalArgumentException("The wallet of an audit event must be a valid wallet address");
        }
    }

    /** An event without a wallet (every event before u2-retention, and the ones that involve none). */
    public AuditEventCommand(
            UUID eventId,
            Optional<UUID> tenantId,
            String actor,
            ActorType actorType,
            String action,
            String targetRef,
            String correlationId,
            Instant occurredAt,
            Map<String, String> details) {
        this(eventId, tenantId, actor, actorType, action, targetRef, correlationId, occurredAt, details, null);
    }

    /** Event before login: no tenant, anonymous actor shown by the masked wallet address. */
    public static AuditEventCommand anonymous(
            String action,
            String maskedActor,
            String targetRef,
            String correlationId,
            Instant occurredAt,
            Map<String, String> details) {
        return new AuditEventCommand(
                UUID.randomUUID(),
                Optional.empty(),
                maskedActor,
                ActorType.ANONYMOUS,
                action,
                targetRef,
                correlationId,
                occurredAt,
                details);
    }

    /**
     * u2-retention (BR2.1): event before login that involves a valid wallet. The actor is the masked address and the
     * wallet goes in its own field; the publisher adds its HMAC and the full address is never recorded.
     *
     * @throws IllegalArgumentException when {@code wallet} is not a valid wallet address (BR2.15)
     */
    public static AuditEventCommand anonymousWallet(
            String action,
            String wallet,
            String targetRef,
            String correlationId,
            Instant occurredAt,
            Map<String, String> details) {
        if (!WalletAddress.isValid(wallet)) {
            throw new IllegalArgumentException("The wallet of an audit event must be a valid wallet address");
        }
        return new AuditEventCommand(
                UUID.randomUUID(),
                Optional.empty(),
                WalletAddress.mask(wallet),
                ActorType.ANONYMOUS,
                action,
                targetRef,
                correlationId,
                occurredAt,
                details,
                wallet);
    }

    /** Event of an authenticated person inside their tenant. */
    public static AuditEventCommand person(
            UUID tenantId,
            UUID userId,
            String action,
            String targetRef,
            String correlationId,
            Instant occurredAt,
            Map<String, String> details) {
        return new AuditEventCommand(
                UUID.randomUUID(),
                Optional.of(tenantId),
                userId.toString(),
                ActorType.PERSON,
                action,
                targetRef,
                correlationId,
                occurredAt,
                details);
    }

    /** Global action of an administrator (BR2.5): actor is the administrator id, no tenant. */
    public static AuditEventCommand admin(
            UUID adminId,
            String action,
            String targetRef,
            String correlationId,
            Instant occurredAt,
            Map<String, String> details) {
        return new AuditEventCommand(
                UUID.randomUUID(),
                Optional.empty(),
                adminId.toString(),
                ActorType.ADMIN,
                action,
                targetRef,
                correlationId,
                occurredAt,
                details);
    }

    /** Action of the system itself, such as a scheduled job (BR3.3): actor {@code system}, no tenant. */
    public static AuditEventCommand system(
            String action, String targetRef, String correlationId, Instant occurredAt, Map<String, String> details) {
        return new AuditEventCommand(
                UUID.randomUUID(),
                Optional.empty(),
                SYSTEM_ACTOR,
                ActorType.SYSTEM,
                action,
                targetRef,
                correlationId,
                occurredAt,
                details);
    }

    /**
     * u2-retention (BR2.1): the same event involving {@code walletAddress} (for example the accepted login of a person
     * or of an administrator, or the creation of an account).
     *
     * @throws IllegalArgumentException when {@code walletAddress} is not a valid wallet address (BR2.15)
     */
    public AuditEventCommand withWallet(String walletAddress) {
        Objects.requireNonNull(walletAddress, "walletAddress");
        return new AuditEventCommand(
                eventId,
                tenantId,
                actor,
                actorType,
                action,
                targetRef,
                correlationId,
                occurredAt,
                details,
                walletAddress,
                real);
    }

    /** Actor of system events. */
    public static final String SYSTEM_ACTOR = "system";

    /** Never prints the full wallet: only whether there is one and its masked form. */
    @Override
    public String toString() {
        return "AuditEventCommand[eventId=" + eventId
                + ", tenantId=" + tenantId
                + ", actor=" + actor
                + ", actorType=" + actorType
                + ", action=" + action
                + ", targetRef=" + targetRef
                + ", correlationId=" + correlationId
                + ", occurredAt=" + occurredAt
                + ", details=" + details
                + ", wallet=" + (wallet == null ? "none" : WalletAddress.mask(wallet))
                + ", real=" + (real == null ? "none" : "typed")
                + "]";
    }

    private static void requireText(String value, String name) {
        if (value == null || value.isBlank()) {
            throw new IllegalArgumentException(name + " is required");
        }
    }
}

package com.memetrade.identity.infra;

import static org.assertj.core.api.Assertions.assertThat;

import com.memetrade.audit.api.AuditEventPublisher;
import com.memetrade.identity.domain.purge.IdentityPurge;
import com.memetrade.identity.domain.purge.PurgeOutcome;
import com.memetrade.identity.domain.purge.PurgeResult;
import com.memetrade.identity.domain.purge.PurgeRunStore;
import com.memetrade.testsupport.TestAccounts;
import com.memetrade.testsupport.TestWallet;
import io.micrometer.core.instrument.Meter;
import io.micrometer.core.instrument.Timer;
import io.micrometer.core.instrument.config.MeterFilter;
import io.micrometer.core.instrument.distribution.DistributionStatisticConfig;
import io.micrometer.core.instrument.distribution.ValueAtPercentile;
import io.micrometer.core.instrument.simple.SimpleMeterRegistry;
import java.sql.Timestamp;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.util.List;
import java.util.concurrent.TimeUnit;
import net.javacrumbs.shedlock.core.LockingTaskExecutor;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.transaction.PlatformTransactionManager;

/**
 * Passo 4 of u2-retention (NFR3.1, NFR3.2, NFR3.5, NFR3.6, performance-design.md "Orçamento por lote"): 100 000 ended
 * sessions (1000 times the daily volume of the beta, one used digest for every tenth) and 100 000 expired challenges,
 * generated by SQL. Each batch of 1000 stays within 500 ms at the 95th percentile, the whole purge within 5 minutes, and
 * the selection of the session purge uses {@code user_session_end_idx}. The runner uses the real UTC clock here, so the
 * durations are real; the rows are placed relative to that clock.
 */
@Tag("u2-retention")
class SessionPurgePerformanceIT extends AbstractIdentityJobIT {

    private static final int ROWS = 100_000;
    private static final Duration BATCH_BUDGET = Duration.ofMillis(500);
    private static final Duration RUN_BUDGET = Duration.ofMinutes(5);

    @Autowired
    private LockingTaskExecutor locks;

    @Autowired
    private PurgeRunStore runs;

    @Autowired
    private AuditEventPublisher audit;

    @Autowired
    private PlatformTransactionManager transactions;

    @Autowired
    private JdbcClient jdbcClient;

    private final Clock realClock = Clock.systemUTC();

    @Test
    void oneHundredThousandEndedSessionsLeaveWithinTheBudgetThroughTheEndIndex() {
        TestAccounts.Seeded owner =
                TestAccounts.betaUser(jdbc, TestWallet.generate().address());
        Instant end = realClock.instant().minus(Duration.ofDays(40));
        seedSessions(owner, end);
        analyze("user_session");
        analyze("session_used_refresh_digest");

        String plan = String.join(
                "\n",
                jdbc.sql("explain select session_id from user_session where "
                                + SessionPurgeJob.SESSION_END
                                + " <= :cutoff order by "
                                + SessionPurgeJob.SESSION_END
                                + " limit 1000")
                        .param("cutoff", Timestamp.from(realClock.instant().minus(Duration.ofDays(30))))
                        .query(String.class)
                        .list());
        assertThat(plan).contains("user_session_end_idx");

        SimpleMeterRegistry registry = percentileRegistry();
        IdentityPurgeProperties settings = IdentityPurgeProperties.defaults();
        IdentityJobRunner measured = runner(registry, settings, new SessionPurgeJob(jdbcClient, settings));

        long started = System.nanoTime();
        PurgeOutcome outcome = measured.runLocked(IdentityPurge.SESSION_PURGE).orElseThrow();
        Duration took = Duration.ofNanos(System.nanoTime() - started);

        assertThat(outcome.result()).isEqualTo(PurgeResult.SUCCEEDED);
        assertThat(outcome.deleted()).isGreaterThanOrEqualTo(ROWS);
        assertThat(outcome.related()).isGreaterThanOrEqualTo(ROWS / 10);
        assertThat(outcome.batches()).isGreaterThanOrEqualTo(ROWS / 1000 + 1);
        assertThat(took).isLessThanOrEqualTo(RUN_BUDGET);
        assertThat(p95(registry, "sessionPurge")).isLessThanOrEqualTo(BATCH_BUDGET);
        assertThat(jdbc.sql("select count(*) from user_session where user_id = :u")
                        .param("u", owner.userId())
                        .query(Long.class)
                        .single())
                .isZero();
    }

    @Test
    void oneHundredThousandExpiredChallengesLeaveWithinTheBudget() {
        Instant expired = realClock.instant().minus(Duration.ofDays(3));
        jdbc.sql("""
                        insert into login_challenge
                          (nonce, wallet_address, domain, chain, message, issued_at, expires_at, state, consumed_at)
                        select 'perf-' || gen_random_uuid(), 'PerfWallet11111111111111111111111111', 'localhost:3000',
                               'solana:mainnet', 'test message', cast(:expires as timestamptz) - interval '1 hour',
                               cast(:expires as timestamptz) - (g % 1000) * interval '1 second', 'EXPIRED', null
                        from generate_series(1, :rows) g
                        """)
                .param("expires", Timestamp.from(expired))
                .param("rows", ROWS)
                .update();
        analyze("login_challenge");

        SimpleMeterRegistry registry = percentileRegistry();
        IdentityPurgeProperties settings = IdentityPurgeProperties.defaults();
        IdentityJobRunner measured = runner(registry, settings, new LoginChallengePurgeJob(jdbcClient, settings));

        long started = System.nanoTime();
        PurgeOutcome outcome =
                measured.runLocked(IdentityPurge.LOGIN_CHALLENGE_PURGE).orElseThrow();
        Duration took = Duration.ofNanos(System.nanoTime() - started);

        assertThat(outcome.result()).isEqualTo(PurgeResult.SUCCEEDED);
        assertThat(outcome.deleted()).isGreaterThanOrEqualTo(ROWS);
        assertThat(took).isLessThanOrEqualTo(RUN_BUDGET);
        assertThat(p95(registry, "loginChallengePurge")).isLessThanOrEqualTo(BATCH_BUDGET);
    }

    private void seedSessions(TestAccounts.Seeded owner, Instant end) {
        jdbc.sql("""
                        insert into user_session
                          (session_id, user_id, tenant_id, role, refresh_token_digest, created_at,
                           refresh_expires_at, absolute_expires_at, state, revoked_at)
                        select gen_random_uuid(), :user, :tenant, 'BETA_USER',
                               md5(gen_random_uuid()::text) || md5(gen_random_uuid()::text),
                               cast(:end as timestamptz) - interval '8 hours',
                               cast(:end as timestamptz) - (g % 100) * interval '1 minute',
                               cast(:end as timestamptz), 'EXPIRED', null
                        from generate_series(1, :rows) g
                        """)
                .param("user", owner.userId())
                .param("tenant", owner.tenantId())
                .param("end", Timestamp.from(end))
                .param("rows", ROWS)
                .update();
        jdbc.sql("""
                        insert into session_used_refresh_digest (digest, session_id, used_at)
                        select md5(gen_random_uuid()::text) || md5(gen_random_uuid()::text), session_id,
                               cast(:end as timestamptz) - interval '1 hour'
                        from (select session_id, row_number() over (order by session_id) as rn
                              from user_session where user_id = :user) numbered
                        where rn % 10 = 0
                        """)
                .param("user", owner.userId())
                .param("end", Timestamp.from(end))
                .update();
    }

    /** ANALYZE needs the owner of the table; the application login cannot run it. */
    private static void analyze(String table) {
        connect(OWNER).sql("analyze " + table).update();
    }

    private IdentityJobRunner runner(
            SimpleMeterRegistry registry, IdentityPurgeProperties settings, IdentityPurgeJob job) {
        return new IdentityJobRunner(
                locks, List.of(job), runs, audit, transactions, new IdentityJobMetrics(registry), settings, realClock);
    }

    /** A registry that keeps the 95th percentile of the batch timer (production exports the plain timer). */
    private static SimpleMeterRegistry percentileRegistry() {
        SimpleMeterRegistry registry = new SimpleMeterRegistry();
        registry.config().meterFilter(new MeterFilter() {
            @Override
            public DistributionStatisticConfig configure(Meter.Id id, DistributionStatisticConfig config) {
                if (!id.getName().equals("memetrade.purge.batch.duration")) {
                    return config;
                }
                return DistributionStatisticConfig.builder()
                        .percentiles(0.95)
                        .expiry(Duration.ofHours(1))
                        .build()
                        .merge(config);
            }
        });
        return registry;
    }

    private static Duration p95(SimpleMeterRegistry registry, String purge) {
        Timer timer = registry.get("memetrade.purge.batch.duration")
                .tag("purge", purge)
                .timer();
        for (ValueAtPercentile value : timer.takeSnapshot().percentileValues()) {
            if (value.percentile() == 0.95) {
                return Duration.ofNanos((long) value.value(TimeUnit.NANOSECONDS));
            }
        }
        throw new AssertionError("no 95th percentile was kept for " + purge);
    }
}

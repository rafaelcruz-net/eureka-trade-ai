package com.memetrade.identity.infra;

import com.memetrade.audit.api.AuditEventPublisher;
import com.memetrade.testsupport.AbstractPostgresIT;
import com.memetrade.testsupport.InMemoryLockProvider;
import com.memetrade.testsupport.TestAccounts;
import com.memetrade.testsupport.TestWallet;
import io.micrometer.core.instrument.simple.SimpleMeterRegistry;
import java.sql.Timestamp;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.util.HexFormat;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.ThreadLocalRandom;
import javax.sql.DataSource;
import net.javacrumbs.shedlock.core.DefaultLockingTaskExecutor;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/**
 * Database fixtures of the Identity purge tests (u2-retention, Passo 2): the PostgreSQL container and the migrations of
 * {@link AbstractPostgresIT}, reached with the APPLICATION login, without a Spring context. Every test clears the
 * purge tables first, so no test depends on another one or on the order. Wallets are generated in test code only.
 */
final class PurgeFixtures {

    /** The fixed instant of the tests (the same default as {@code MutableClock}). */
    static final Instant NOW = Instant.parse("2026-10-28T12:00:00Z");

    final DataSource dataSource;
    final JdbcClient jdbc;
    final DataSourceTransactionManager transactions;
    final SimpleMeterRegistry meters = new SimpleMeterRegistry();

    private PurgeFixtures(DataSource dataSource) {
        this.dataSource = dataSource;
        this.jdbc = JdbcClient.create(dataSource);
        this.transactions = new DataSourceTransactionManager(dataSource);
    }

    static PurgeFixtures connect() {
        return new PurgeFixtures(new DriverManagerDataSource(
                AbstractPostgresIT.jdbcUrl(), AbstractPostgresIT.APP.user(), AbstractPostgresIT.APP.password()));
    }

    void clearChallenges() {
        jdbc.sql("delete from login_challenge").update();
    }

    void clearSessions() {
        jdbc.sql("delete from session_used_refresh_digest").update();
        jdbc.sql("delete from user_session").update();
    }

    void clearRuns() {
        jdbc.sql("delete from identity_job_run").update();
    }

    /** One challenge in {@code state} (ISSUED, CONSUMED or EXPIRED) that expires at {@code expiresAt}. */
    String challenge(String state, Instant expiresAt) {
        String nonce = "purge-" + UUID.randomUUID();
        Instant issuedAt = expiresAt.minus(Duration.ofMinutes(5));
        jdbc.sql("""
                        insert into login_challenge
                          (nonce, wallet_address, domain, chain, message, issued_at, expires_at, state, consumed_at)
                        values (:nonce, :wallet, 'localhost:3000', 'solana:mainnet', 'test message', :issued,
                                :expires, :state, :consumed)
                        """)
                .param("nonce", nonce)
                .param("wallet", TestWallet.generate().address())
                .param("issued", Timestamp.from(issuedAt))
                .param("expires", Timestamp.from(expiresAt))
                .param("state", state)
                .param("consumed", "CONSUMED".equals(state) ? Timestamp.from(issuedAt.plusSeconds(1)) : null)
                .update();
        return nonce;
    }

    /** {@code count} ISSUED challenges expiring at {@code expiresAt}, generated by SQL. */
    void challenges(int count, Instant expiresAt) {
        jdbc.sql("""
                        insert into login_challenge
                          (nonce, wallet_address, domain, chain, message, issued_at, expires_at, state, consumed_at)
                        select 'bulk-' || gen_random_uuid(), 'BulkWallet1111111111111111111111111', 'localhost:3000',
                               'solana:mainnet', 'test message', cast(:expires as timestamptz) - interval '5 minutes',
                               cast(:expires as timestamptz), 'ISSUED', null
                        from generate_series(1, :count)
                        """)
                .param("expires", Timestamp.from(expiresAt))
                .param("count", count)
                .update();
    }

    boolean challengeExists(String nonce) {
        return jdbc.sql("select count(*) from login_challenge where nonce = :n")
                        .param("n", nonce)
                        .query(Long.class)
                        .single()
                == 1L;
    }

    long challengeCount() {
        return jdbc.sql("select count(*) from login_challenge")
                .query(Long.class)
                .single();
    }

    /** A guest account (tenant, user and wallet) for the sessions of a test. */
    TestAccounts.Seeded person() {
        return TestAccounts.betaUser(jdbc, TestWallet.generate().address());
    }

    /**
     * A session of {@code owner} with role {@code role} and state {@code state}; {@code revokedAt} may be null.
     * {@code refreshExpiresAt} must not be after {@code absoluteExpiresAt} (constraint of migration 0001).
     */
    UUID session(
            TestAccounts.Seeded owner,
            String role,
            String state,
            Instant refreshExpiresAt,
            Instant absoluteExpiresAt,
            Instant revokedAt) {
        UUID id = UUID.randomUUID();
        Instant createdAt = refreshExpiresAt.minus(Duration.ofHours(8));
        jdbc.sql("""
                        insert into user_session
                          (session_id, user_id, tenant_id, role, refresh_token_digest, created_at,
                           refresh_expires_at, absolute_expires_at, state, revoked_at)
                        values (:id, :user, :tenant, :role, :digest, :created, :refresh, :absolute, :state, :revoked)
                        """)
                .param("id", id)
                .param("user", owner.userId())
                .param("tenant", owner.tenantId())
                .param("role", role)
                .param("digest", randomDigest())
                .param("created", Timestamp.from(createdAt))
                .param("refresh", Timestamp.from(refreshExpiresAt))
                .param("absolute", Timestamp.from(absoluteExpiresAt))
                .param("state", state)
                .param("revoked", revokedAt == null ? null : Timestamp.from(revokedAt))
                .update();
        return id;
    }

    /** A session that ended (by its expirations) at {@code end}, never revoked. */
    UUID endedSession(TestAccounts.Seeded owner, Instant end) {
        return session(owner, "BETA_USER", "ACTIVE", end, end, null);
    }

    void digests(UUID sessionId, int count) {
        for (int i = 0; i < count; i++) {
            jdbc.sql("insert into session_used_refresh_digest (digest, session_id, used_at) values (:d, :s, :at)")
                    .param("d", randomDigest())
                    .param("s", sessionId)
                    .param("at", Timestamp.from(NOW.minus(Duration.ofDays(60))))
                    .update();
        }
    }

    boolean sessionExists(UUID sessionId) {
        return jdbc.sql("select count(*) from user_session where session_id = :id")
                        .param("id", sessionId)
                        .query(Long.class)
                        .single()
                == 1L;
    }

    long digestsOf(UUID sessionId) {
        return jdbc.sql("select count(*) from session_used_refresh_digest where session_id = :id")
                .param("id", sessionId)
                .query(Long.class)
                .single();
    }

    /** The common executor over this database, with an in-memory lock, the given jobs and the recording publisher. */
    IdentityJobRunner runner(
            Clock clock, AuditEventPublisher audit, IdentityPurgeProperties settings, List<IdentityPurgeJob> jobs) {
        return new IdentityJobRunner(
                new DefaultLockingTaskExecutor(new InMemoryLockProvider()),
                jobs,
                new JdbcIdentityJobRunStore(jdbc),
                audit,
                transactions,
                new IdentityJobMetrics(meters),
                settings,
                clock);
    }

    /** The defaults of application.yml with another batch size. */
    static IdentityPurgeProperties withBatchSize(int batchSize) {
        IdentityPurgeProperties defaults = IdentityPurgeProperties.defaults();
        return new IdentityPurgeProperties(
                defaults.challengesCron(),
                defaults.sessionsCron(),
                defaults.challengeRetention(),
                defaults.sessionRetention(),
                batchSize,
                defaults.lockAtMostFor(),
                defaults.lockAtLeastFor(),
                defaults.recoverAfter(),
                defaults.degradedAfter());
    }

    private static String randomDigest() {
        byte[] bytes = new byte[32];
        ThreadLocalRandom.current().nextBytes(bytes);
        return HexFormat.of().formatHex(bytes);
    }
}

package com.memetrade.marketdata.infra.coingecko;

import static com.github.tomakehurst.wiremock.client.WireMock.aResponse;
import static com.github.tomakehurst.wiremock.client.WireMock.equalTo;
import static com.github.tomakehurst.wiremock.client.WireMock.get;
import static com.github.tomakehurst.wiremock.client.WireMock.getRequestedFor;
import static com.github.tomakehurst.wiremock.client.WireMock.okJson;
import static com.github.tomakehurst.wiremock.client.WireMock.urlEqualTo;
import static com.github.tomakehurst.wiremock.client.WireMock.urlPathEqualTo;
import static com.github.tomakehurst.wiremock.client.WireMock.urlPathMatching;
import static com.github.tomakehurst.wiremock.core.WireMockConfiguration.wireMockConfig;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.assertj.core.api.Assertions.catchThrowableOfType;

import ch.qos.logback.classic.Logger;
import ch.qos.logback.classic.spi.ILoggingEvent;
import ch.qos.logback.core.read.ListAppender;
import com.fasterxml.jackson.databind.JsonNode;
import com.github.tomakehurst.wiremock.junit5.WireMockExtension;
import com.memetrade.marketdata.api.FailureCategory;
import com.memetrade.marketdata.infra.coingecko.CoinGeckoCallException.Kind;
import java.time.Duration;
import java.util.List;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.RegisterExtension;
import org.slf4j.LoggerFactory;

/**
 * Step 4 (NFR1.1 to NFR1.3, security-design.md): the HTTPS client against a WireMock double with synthetic answers. The
 * real CoinGecko is never called; every mint is generated by {@link CoinGeckoFixtures}.
 */
class CoinGeckoHttpTest {

    @RegisterExtension
    static WireMockExtension wire = WireMockExtension.newInstance()
            .options(wireMockConfig().dynamicPort())
            .build();

    private static final String KEY = CoinGeckoFixtures.TEST_KEY;
    private static final String MINT_A = CoinGeckoFixtures.mint(1);
    private static final String MINT_B = CoinGeckoFixtures.mint(2);

    private CoinGeckoHttp http;
    private ListAppender<ILoggingEvent> logs;
    private Logger root;

    @BeforeEach
    void setUp() {
        http = new CoinGeckoHttp(
                wire.baseUrl() + "/api/v3", "x-cg-pro-api-key", KEY, Duration.ofSeconds(2), Duration.ofMillis(2_500));
        root = (Logger) LoggerFactory.getLogger(org.slf4j.Logger.ROOT_LOGGER_NAME);
        logs = new ListAppender<>();
        logs.start();
        root.addAppender(logs);
    }

    @AfterEach
    void tearDown() {
        root.detachAppender(logs);
    }

    @Test
    void pricesTravelWithTheKeyInTheHeaderAndAskForAnUncompressedBody() {
        wire.stubFor(get(urlPathMatching("/api/v3/onchain/simple/networks/solana/token_price/.*"))
                .willReturn(okJson(CoinGeckoFixtures.prices(List.of(MINT_A, MINT_B)))));

        JsonNode answer = http.tokenPrices("solana", List.of(MINT_A, MINT_B));

        assertThat(answer.at("/data/attributes/token_prices/" + MINT_A).asText())
                .isNotBlank();
        wire.verify(getRequestedFor(urlEqualTo("/api/v3/onchain/simple/networks/solana/token_price/" + MINT_A + ","
                        + MINT_B + "?include_24hr_vol=true&include_total_reserve_in_usd=true"))
                .withHeader("x-cg-pro-api-key", equalTo(KEY))
                .withHeader("Accept-Encoding", equalTo("identity")));
    }

    @Test
    void jsonNumbersAreReadAsExactDecimalsNeverFloatingPoint() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key"))
                .willReturn(okJson("{\"value\": 0.000000123456789012345678, \"calls\": 12}")));

        JsonNode answer = http.keyUsage();

        assertThat(answer.get("value").isBigDecimal()).isTrue();
        assertThat(answer.get("value").decimalValue().toPlainString()).isEqualTo("0.000000123456789012345678");
    }

    @Test
    void aRedirectIsNeverFollowedAndIsNotRetryable() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key"))
                .willReturn(aResponse().withStatus(302).withHeader("Location", wire.baseUrl() + "/elsewhere")));
        wire.stubFor(get(urlPathEqualTo("/elsewhere")).willReturn(okJson("{}")));

        CoinGeckoCallException failure = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);

        assertThat(failure.kind()).isEqualTo(Kind.REDIRECT);
        assertThat(failure.retryable()).isFalse();
        wire.verify(0, getRequestedFor(urlPathEqualTo("/elsewhere")));
    }

    @Test
    void aCompressedAnswerIsRefused() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key"))
                .willReturn(aResponse()
                        .withStatus(200)
                        .withHeader("Content-Encoding", "gzip")
                        .withBody("{}")));

        CoinGeckoCallException failure = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);

        assertThat(failure.kind()).isEqualTo(Kind.INVALID_PAYLOAD);
        assertThat(failure.category()).isEqualTo(FailureCategory.INVALID_PAYLOAD);
        assertThat(failure.retryable()).isFalse();
    }

    @Test
    void aBodyLargerThanTwoMegabytesIsCutAndRefused() {
        String huge = "[" + "0,".repeat(1_100_000) + "0]";
        wire.stubFor(get(urlPathEqualTo("/api/v3/key")).willReturn(okJson(huge)));

        CoinGeckoCallException failure = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);

        assertThat(failure.kind()).isEqualTo(Kind.INVALID_PAYLOAD);
    }

    @Test
    void aTooDeepOrMalformedJsonIsRefused() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key")).willReturn(okJson("[".repeat(40) + "]".repeat(40))));
        assertThat(catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage)
                        .kind())
                .isEqualTo(Kind.INVALID_PAYLOAD);

        wire.stubFor(get(urlPathEqualTo("/api/v3/key")).willReturn(okJson("{\"data\": [1, 2")));
        assertThat(catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage)
                        .kind())
                .isEqualTo(Kind.INVALID_PAYLOAD);
    }

    @Test
    void anInvalidMintIsNeverRequested() {
        assertThatThrownBy(() -> http.tokenInfo("solana", "../../key")).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> http.tokenPrices("solana", List.of(MINT_A, "0OIl" + MINT_B.substring(4))))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> http.tokenPools("solana", "short")).isInstanceOf(IllegalArgumentException.class);

        assertThat(wire.getAllServeEvents()).isEmpty();
    }

    @Test
    void a429CarriesItsRetryAfterAndIsNotRetried() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key"))
                .willReturn(aResponse().withStatus(429).withHeader("Retry-After", "7")));

        CoinGeckoCallException failure = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);

        assertThat(failure.kind()).isEqualTo(Kind.RATE_LIMITED);
        assertThat(failure.retryAfter()).contains(Duration.ofSeconds(7));
        assertThat(failure.retryable()).isFalse();
        assertThat(failure.category()).isEqualTo(FailureCategory.ERROR_RESPONSE);
    }

    @Test
    void a5xxIsARetryableTechnicalFailureAndAnother4xxIsNot() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key")).willReturn(aResponse().withStatus(503)));
        CoinGeckoCallException server = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);
        assertThat(server.kind()).isEqualTo(Kind.SERVER_ERROR);
        assertThat(server.retryable()).isTrue();
        assertThat(server.technical()).isTrue();

        wire.stubFor(get(urlPathEqualTo("/api/v3/key")).willReturn(aResponse().withStatus(401)));
        CoinGeckoCallException client = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);
        assertThat(client.kind()).isEqualTo(Kind.CLIENT_ERROR);
        assertThat(client.retryable()).isFalse();
        assertThat(client.technical()).isFalse();
    }

    @Test
    void aSlowAnswerTimesOutAsARetryableTimeout() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key")).willReturn(okJson("{}").withFixedDelay(4_000)));

        CoinGeckoCallException failure = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);

        assertThat(failure.kind()).isEqualTo(Kind.TIMEOUT);
        assertThat(failure.category()).isEqualTo(FailureCategory.TIMEOUT);
        assertThat(failure.retryable()).isTrue();
    }

    @Test
    void theKeyAndTheUrlNeverAppearInALogOrAnErrorMessage() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key")).willReturn(aResponse().withStatus(500)));
        CoinGeckoCallException server = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);
        wire.stubFor(get(urlPathEqualTo("/api/v3/key")).willReturn(aResponse().withStatus(403)));
        CoinGeckoCallException forbidden = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);
        CoinGeckoHttp unreachable = new CoinGeckoHttp(
                "http://127.0.0.1:1/api/v3", "x-cg-pro-api-key", KEY, Duration.ofMillis(300), Duration.ofMillis(300));
        CoinGeckoCallException network = catchThrowableOfType(CoinGeckoCallException.class, unreachable::keyUsage);

        for (CoinGeckoCallException failure : List.of(server, forbidden, network)) {
            assertThat(failure.getMessage())
                    .startsWith("key_usage ")
                    .doesNotContain(KEY)
                    .doesNotContain("/api/v3")
                    .doesNotContain("127.0.0.1");
        }
        assertThat(network.kind()).isIn(Kind.NETWORK, Kind.TIMEOUT);
        assertThat(http.toString()).doesNotContain(KEY);
        assertThat(logs.list)
                .allSatisfy(event -> assertThat(event.getFormattedMessage()).doesNotContain(KEY));
    }

    @Test
    void theRoutesUseTheNetworkAndTheValidatedMint() {
        wire.stubFor(get(urlPathMatching("/api/v3/onchain/networks/solana/.*")).willReturn(okJson("{\"data\": []}")));

        http.newPools("solana");
        http.trendingPools("solana");
        http.tokenInfo("solana", MINT_A);
        http.tokenPools("solana", MINT_A);

        wire.verify(getRequestedFor(urlEqualTo("/api/v3/onchain/networks/solana/new_pools?include=base_token&page=1")));
        wire.verify(getRequestedFor(
                urlEqualTo("/api/v3/onchain/networks/solana/trending_pools?include=base_token&page=1")));
        wire.verify(getRequestedFor(urlEqualTo("/api/v3/onchain/networks/solana/tokens/" + MINT_A + "/info")));
        wire.verify(getRequestedFor(urlEqualTo("/api/v3/onchain/networks/solana/tokens/" + MINT_A + "/pools?page=1")));
        assertThatThrownBy(() -> http.newPools("Solana/../x")).isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void aBodyThatTricklesInPastTheDeadlineIsATimeout() {
        wire.stubFor(get(urlPathEqualTo("/api/v3/key"))
                .willReturn(okJson("{\"current_total_monthly_calls\": 12, \"padding\": \"" + "x".repeat(200) + "\"}")
                        .withChunkedDribbleDelay(20, 8_000)));
        long started = System.nanoTime();

        CoinGeckoCallException failure = catchThrowableOfType(CoinGeckoCallException.class, http::keyUsage);

        assertThat(failure.kind()).isEqualTo(Kind.TIMEOUT);
        assertThat(failure.retryable()).isTrue();
        assertThat(Duration.ofNanos(System.nanoTime() - started))
                .as("cut at the 2.5 s deadline of the call, not after the 8 s body")
                .isLessThan(Duration.ofMillis(5_000));
    }

    @Test
    void theRetryAfterHeaderIsReadOnlyAsWholeSecondsAndCapped() {
        assertThat(CoinGeckoHttp.retryAfter("12")).contains(Duration.ofSeconds(12));
        assertThat(CoinGeckoHttp.retryAfter("999999")).contains(Duration.ofHours(1));
        assertThat(CoinGeckoHttp.retryAfter("Wed, 21 Oct 2026 07:28:00 GMT")).isEmpty();
        assertThat(CoinGeckoHttp.retryAfter(null)).isEmpty();
    }
}

/**
 * Step 3 of the U4 (deviation of Q2, U4-NFR1.1): the COMMON Solana vectors of the api and the TxSigner, generated by
 * the Solana SDK in TEST scope only. Every key comes from a fixed seed and Ed25519 is deterministic, so the generation
 * gives the same bytes on every run: this test regenerates the vectors in memory and compares them with the versioned
 * file, and {@code -Dsolana.vectors.write=true} writes them to both apps
 * ({@code apps/api/src/test/resources/solana-vectors/vectors.json} and the same path under {@code apps/txsigner}).
 *
 * <p>The keys and the mints are synthetic (team.md: fixtures never use a real wallet nor a real mint); the program ids
 * are the public ones. The swap messages follow the shape of the Jupiter swap-instructions of a buy and a sell with SOL
 * wrapped and unwrapped in the bot wallet, so the TxSigner uses them as the transactions that must pass its policy
 * until real transactions are recorded by {@code infra/solana-fixtures/record.sh}.
 */
@Tag("u4-real-execution")
class SolanaVectorsGenerationTest {

    static final Path API_FILE = Path.of("src", "test", "resources", "solana-vectors", "vectors.json");
    static final Path TXSIGNER_FILE =
            Path.of("..", "txsigner", "src", "test", "resources", "solana-vectors", "vectors.json");

    static final String SYSTEM = "11111111111111111111111111111111";
    static final String TOKEN = "TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA";
    static final String TOKEN_2022 = "TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb";
    static final String ATA = "ATokenGPvbdGVxr1b2hvZbsiqW5xWH25efTNsLJA8knL";
    static final String COMPUTE_BUDGET = "ComputeBudget111111111111111111111111111111";
    static final String JUPITER = "JUP6LkbZbjS1jKKwapdHNy74zcZ3tLUZoi5QNyVTaV4";
    static final String JUPITER_EVENT_AUTHORITY = "D8cy77BBepLMngZx6ZukaTff5hCt1HrWyKk3Hnd9oitf";
    static final String WSOL = "So11111111111111111111111111111111111111112";

    private static final ObjectMapper JSON = new ObjectMapper().enable(SerializationFeature.INDENT_OUTPUT);
    private static final HexFormat HEX = HexFormat.of();

    @Test
    void theVersionedVectorsAreWhatTheSdkGeneratesToday() throws Exception {
        String generated = JSON.writeValueAsString(vectors()) + "\n";
        if (Boolean.getBoolean("solana.vectors.write")) {
            for (Path file : List.of(API_FILE, TXSIGNER_FILE)) {
                Files.createDirectories(file.getParent());
                Files.writeString(file, generated, StandardCharsets.UTF_8);
            }
        }

        assertThat(Files.readString(API_FILE, StandardCharsets.UTF_8)).isEqualTo(generated);
    }

    static ObjectNode vectors() throws Exception {
        ObjectNode root = JSON.createObjectNode();
        root.put("version", 1);
        root.put("generator", "solanaj 1.28.0, test scope only (SolanaVectorsGenerationTest)");
        root.set("base58", base58());
        root.set("ata", associatedTokenAccounts());
        root.set("signatures", signatures());
        root.set("messages", messages());
        return root;
    }

    /** A synthetic wallet from a fixed seed (never a real wallet). */
    static Account wallet(int seed) {
        byte[] bytes = new byte[32];
        Arrays.fill(bytes, (byte) seed);
        TweetNaclFast.Signature.KeyPair pair = TweetNaclFast.Signature.keyPair_fromSeed(bytes);
        return new Account(pair.getSecretKey());
    }

    /** A synthetic mint (32 bytes filled with {@code value}); never a real mint. */
    static PublicKey syntheticKey(int value) {
        byte[] bytes = new byte[32];
        Arrays.fill(bytes, (byte) value);
        return new PublicKey(bytes);
    }

    private static ArrayNode base58() {
        ArrayNode list = JSON.createArrayNode();
        List<byte[]> inputs = new ArrayList<>();
        inputs.add(new byte[32]);
        byte[] leading = new byte[32];
        leading[2] = 1;
        leading[31] = (byte) 0xff;
        inputs.add(leading);
        inputs.add(syntheticKey(7).toByteArray());
        inputs.add(wallet(1).getPublicKey().toByteArray());
        byte[] signature = new byte[64];
        for (int i = 0; i < signature.length; i++) {
            signature[i] = (byte) (i * 13 + 5);
        }
        inputs.add(signature);
        for (byte[] input : inputs) {
            ObjectNode item = list.addObject();
            item.put("hex", HEX.formatHex(input));
            item.put("base58", org.p2p.solanaj.utils.Base58.encode(input));
        }
        return list;
    }

    private static ArrayNode associatedTokenAccounts() throws Exception {
        ArrayNode list = JSON.createArrayNode();
        for (int owner = 1; owner <= 3; owner++) {
            for (String tokenProgram : List.of(TOKEN, TOKEN_2022)) {
                for (PublicKey mint : List.of(syntheticKey(40 + owner), new PublicKey(WSOL))) {
                    PublicKey wallet = wallet(owner).getPublicKey();
                    ObjectNode item = list.addObject();
                    item.put("owner", wallet.toBase58());
                    item.put("tokenProgram", tokenProgram);
                    item.put("mint", mint.toBase58());
                    item.put(
                            "address",
                            ata(wallet, new PublicKey(tokenProgram), mint).toBase58());
                }
            }
        }
        return list;
    }

    static PublicKey ata(PublicKey owner, PublicKey tokenProgram, PublicKey mint) throws Exception {
        return PublicKey.findProgramAddress(
                        List.of(owner.toByteArray(), tokenProgram.toByteArray(), mint.toByteArray()),
                        new PublicKey(ATA))
                .getAddress();
    }

    private static ArrayNode signatures() {
        ArrayNode list = JSON.createArrayNode();
        int seed = 1;
        for (String text : List.of("", "Eureka Trader - vetor 1", "mensagem de teste com acentuação")) {
            Account account = wallet(seed++);
            byte[] message = text.getBytes(StandardCharsets.UTF_8);
            byte[] signature = new TweetNaclFast.Signature(new byte[0], account.getSecretKey()).detached(message);
            ObjectNode item = list.addObject();
            item.put("publicKey", account.getPublicKey().toBase58());
            item.put("messageHex", HEX.formatHex(message));
            item.put("signature", org.p2p.solanaj.utils.Base58.encode(signature));
        }
        return list;
    }

    private static ArrayNode messages() throws Exception {
        ArrayNode list = JSON.createArrayNode();
        Account bot = wallet(11);
        Account main = wallet(12);
        PublicKey token = syntheticKey(43);
        String blockhash = syntheticKey(9).toBase58();
        list.add(message("auto-full-buy", List.of(bot), buy(bot.getPublicKey(), token, 50_000_000L), blockhash));
        list.add(message("signed-buy", List.of(main, bot), buy(bot.getPublicKey(), token, 50_000_000L), blockhash));
        list.add(message("auto-full-sell", List.of(bot), sell(bot.getPublicKey(), token, 987_654_321L), blockhash));
        list.add(message("signed-sell", List.of(main, bot), sell(bot.getPublicKey(), token, 987_654_321L), blockhash));
        return list;
    }

    /** A buy of {@code token} with {@code lamports}: wrap SOL, create the token account, route, unwrap the rest. */
    static List<TransactionInstruction> buy(PublicKey bot, PublicKey token, long lamports) throws Exception {
        PublicKey wsolAccount = ata(bot, new PublicKey(TOKEN), new PublicKey(WSOL));
        PublicKey tokenAccount = ata(bot, new PublicKey(TOKEN), token);
        List<TransactionInstruction> list = new ArrayList<>();
        list.add(computeUnitLimit(280_000));
        list.add(computeUnitPrice(12_345L));
        list.add(createIdempotent(bot, wsolAccount, bot, new PublicKey(WSOL)));
        list.add(transfer(bot, wsolAccount, lamports));
        list.add(syncNative(wsolAccount));
        list.add(createIdempotent(bot, tokenAccount, bot, token));
        list.add(route(bot, wsolAccount, tokenAccount, token, lamports, 123_456_789L, 200));
        list.add(closeAccount(wsolAccount, bot, bot));
        return list;
    }

    /** A sell of {@code units} of {@code token} for SOL: create the wrapped SOL account, route, unwrap. */
    static List<TransactionInstruction> sell(PublicKey bot, PublicKey token, long units) throws Exception {
        PublicKey wsolAccount = ata(bot, new PublicKey(TOKEN), new PublicKey(WSOL));
        PublicKey tokenAccount = ata(bot, new PublicKey(TOKEN), token);
        List<TransactionInstruction> list = new ArrayList<>();
        list.add(computeUnitLimit(250_000));
        list.add(computeUnitPrice(10_000L));
        list.add(createIdempotent(bot, wsolAccount, bot, new PublicKey(WSOL)));
        list.add(route(bot, tokenAccount, wsolAccount, new PublicKey(WSOL), units, 48_000_000L, 300));
        list.add(closeAccount(wsolAccount, bot, bot));
        return list;
    }

    private static ObjectNode message(
            String name, List<Account> signers, List<TransactionInstruction> instructions, String blockhash) {
        Transaction transaction = new Transaction();
        instructions.forEach(transaction::addInstruction);
        transaction.setRecentBlockHash(blockhash);
        transaction.sign(signers);
        byte[] wire = transaction.serialize();
        int signatureCount = wire[0];
        byte[] legacy = Arrays.copyOfRange(wire, 1 + 64 * signatureCount, wire.length);

        ObjectNode item = JSON.createObjectNode();
        item.put("name", name);
        item.put("feePayer", signers.getFirst().getPublicKey().toBase58());
        ArrayNode signerList = item.putArray("signers");
        signers.forEach(signer -> signerList.add(signer.getPublicKey().toBase58()));
        item.put("blockhash", blockhash);
        ArrayNode list = item.putArray("instructions");
        for (TransactionInstruction instruction : instructions) {
            ObjectNode ix = list.addObject();
            ix.put("programId", instruction.getProgramId().toBase58());
            ArrayNode accounts = ix.putArray("accounts");
            for (AccountMeta meta : instruction.getKeys()) {
                ObjectNode account = accounts.addObject();
                account.put("pubkey", meta.getPublicKey().toBase58());
                account.put("signer", meta.isSigner());
                account.put("writable", meta.isWritable());
            }
            ix.put("dataHex", HEX.formatHex(instruction.getData()));
        }
        item.put("legacyMessageHex", HEX.formatHex(legacy));
        item.put("signedTransactionBase64", Base64.getEncoder().encodeToString(wire));
        return item;
    }

    static TransactionInstruction computeUnitLimit(int units) {
        return new TransactionInstruction(
                new PublicKey(COMPUTE_BUDGET), List.of(), concat(new byte[] {2}, le(units, 4)));
    }

    static TransactionInstruction computeUnitPrice(long microLamports) {
        return new TransactionInstruction(
                new PublicKey(COMPUTE_BUDGET), List.of(), concat(new byte[] {3}, le(microLamports, 8)));
    }

    static TransactionInstruction createIdempotent(
            PublicKey funder, PublicKey account, PublicKey owner, PublicKey mint) {
        return new TransactionInstruction(
                new PublicKey(ATA),
                List.of(
                        new AccountMeta(funder, true, true),
                        new AccountMeta(account, false, true),
                        new AccountMeta(owner, false, false),
                        new AccountMeta(mint, false, false),
                        new AccountMeta(new PublicKey(SYSTEM), false, false),
                        new AccountMeta(new PublicKey(TOKEN), false, false)),
                new byte[] {1});
    }

    static TransactionInstruction transfer(PublicKey from, PublicKey to, long lamports) {
        return new TransactionInstruction(
                new PublicKey(SYSTEM),
                List.of(new AccountMeta(from, true, true), new AccountMeta(to, false, true)),
                concat(le(2, 4), le(lamports, 8)));
    }

    static TransactionInstruction syncNative(PublicKey account) {
        return new TransactionInstruction(
                new PublicKey(TOKEN), List.of(new AccountMeta(account, false, true)), new byte[] {17});
    }

    static TransactionInstruction closeAccount(PublicKey account, PublicKey destination, PublicKey owner) {
        return new TransactionInstruction(
                new PublicKey(TOKEN),
                List.of(
                        new AccountMeta(account, false, true),
                        new AccountMeta(destination, false, true),
                        new AccountMeta(owner, true, false)),
                new byte[] {9});
    }

    /**
     * The {@code route} instruction of the Jupiter v6 program: token program, user transfer authority (signer), user
     * source and destination token accounts, the optional destination token account and platform fee account set to
     * the program id (None), the destination mint, the event authority and the program, then the accounts of the
     * route (synthetic pools). Data: the Anchor discriminator, a synthetic route plan, then in amount, quoted out
     * amount, slippage in basis points and platform fee in basis points.
     */
    static TransactionInstruction route(
            PublicKey bot,
            PublicKey source,
            PublicKey destination,
            PublicKey destinationMint,
            long inAmount,
            long quotedOut,
            int slippageBps)
            throws Exception {
        PublicKey jupiter = new PublicKey(JUPITER);
        List<AccountMeta> accounts = new ArrayList<>(List.of(
                new AccountMeta(new PublicKey(TOKEN), false, false),
                new AccountMeta(bot, true, false),
                new AccountMeta(source, false, true),
                new AccountMeta(destination, false, true),
                new AccountMeta(jupiter, false, false),
                new AccountMeta(destinationMint, false, false),
                new AccountMeta(jupiter, false, false),
                new AccountMeta(new PublicKey(JUPITER_EVENT_AUTHORITY), false, false),
                new AccountMeta(jupiter, false, false)));
        for (int pool = 0; pool < 5; pool++) {
            accounts.add(new AccountMeta(syntheticKey(60 + pool), false, pool % 2 == 0));
        }
        byte[] discriminator = Arrays.copyOf(
                MessageDigest.getInstance("SHA-256").digest("global:route".getBytes(StandardCharsets.UTF_8)), 8);
        byte[] routePlan = {1, 0, 0, 0, 7, 100, 0, 1};
        ByteBuffer tail = ByteBuffer.allocate(19).order(ByteOrder.LITTLE_ENDIAN);
        tail.putLong(inAmount).putLong(quotedOut).putShort((short) slippageBps).put((byte) 0);
        return new TransactionInstruction(jupiter, accounts, concat(concat(discriminator, routePlan), tail.array()));
    }

    static byte[] le(long value, int length) {
        byte[] bytes = new byte[length];
        for (int i = 0; i < length; i++) {
            bytes[i] = (byte) (value >>> (8 * i));
        }
        return bytes;
    }

    static byte[] concat(byte[] first, byte[] second) {
        byte[] out = Arrays.copyOf(first, first.length + second.length);
        System.arraycopy(second, 0, out, first.length, second.length);
        return out;
    }
}
